using System.Diagnostics.CodeAnalysis;
using Microsoft.Extensions.VectorData;
using Microsoft.Extensions.VectorData.ProviderServices;

namespace PinkRooster.Extensions.VectorData.LanceDB.Internal;

internal sealed class LanceDbModelBuilder : CollectionModelBuilder
{
    private readonly string _defaultDistanceFunction;

    public LanceDbModelBuilder(string defaultDistanceFunction)
        : base(new CollectionModelBuildingOptions
        {
            SupportsMultipleVectors = true,
            RequiresAtLeastOneVector = false,
            UsesExternalSerializer = false,
        })
    {
        _defaultDistanceFunction = defaultDistanceFunction;
    }

    protected override bool IsDataPropertyTypeValid(Type type, [NotNullWhen(false)] out string? supportedTypes)
    {
        if (LanceDbDataTypes.Classify(type) != LanceDbDataKind.Unsupported)
        {
            supportedTypes = null;
            return true;
        }

        supportedTypes = "string, bool, sbyte, byte, short, ushort, int, uint, long, ulong, float, double, Guid, DateTime, DateTimeOffset, DateOnly, TimeOnly, string[]";
        return false;
    }

    protected override bool IsVectorPropertyTypeValid(Type type, [NotNullWhen(false)] out string? supportedTypes)
    {
        Type underlying = Nullable.GetUnderlyingType(type) ?? type;

        if (underlying == typeof(ReadOnlyMemory<float>) ||
            underlying == typeof(float[]) ||
            (underlying.IsGenericType && underlying.GetGenericTypeDefinition() == typeof(Microsoft.Extensions.AI.Embedding<>) && underlying.GenericTypeArguments[0] == typeof(float)))
        {
            supportedTypes = null;
            return true;
        }

        if (underlying == typeof(ReadOnlyMemory<Half>) ||
            underlying == typeof(Half[]) ||
            (underlying.IsGenericType && underlying.GetGenericTypeDefinition() == typeof(Microsoft.Extensions.AI.Embedding<>) && underlying.GenericTypeArguments[0] == typeof(Half)))
        {
            throw new NotSupportedException("Half-precision (float16) vectors are not supported by the LanceDB provider in v1.");
        }

        supportedTypes = "ReadOnlyMemory<float>, float[], Embedding<float>";
        return false;
    }

    protected override void ValidateProperty(PropertyModel propertyModel, VectorStoreCollectionDefinition? definition)
    {
        base.ValidateProperty(propertyModel, definition);

        if (propertyModel is DataPropertyModel dataProperty)
        {
            if (dataProperty.IsFullTextIndexed && dataProperty.Type != typeof(string))
            {
                throw new NotSupportedException($"Full-text indexing is only supported on string properties. Property '{dataProperty.ModelName}' is of type '{dataProperty.Type.Name}'.");
            }
        }

        if (propertyModel is VectorPropertyModel vectorProperty)
        {
            if (vectorProperty.EmbeddingType == typeof(Half))
            {
                throw new NotSupportedException("Half-precision (float16) vectors are not supported by the LanceDB provider in v1.");
            }

            vectorProperty.DistanceFunction = string.IsNullOrEmpty(vectorProperty.DistanceFunction)
                ? _defaultDistanceFunction
                : vectorProperty.DistanceFunction;
            _ = LanceDbDistanceMetric.FromName(vectorProperty.DistanceFunction);

            if (!string.IsNullOrEmpty(vectorProperty.IndexKind))
            {
                if (vectorProperty.IndexKind == IndexKind.DiskAnn ||
                    vectorProperty.IndexKind == IndexKind.QuantizedFlat ||
                    vectorProperty.IndexKind == IndexKind.Dynamic)
                {
                    throw new NotSupportedException($"Index kind '{vectorProperty.IndexKind}' is not supported by the LanceDB provider.");
                }
            }
        }
    }

    // Guid keys are auto-generated by default in MEVD; this provider never generates keys, so the default (for example the one DataIngestion's writer uses) means "not generated".
    protected override bool SupportsKeyAutoGeneration(Type keyPropertyType) => false;

    protected override void ValidateKeyProperty(KeyPropertyModel keyProperty)
    {
        base.ValidateKeyProperty(keyProperty);

        if (keyProperty.IsAutoGenerated)
        {
            throw new NotSupportedException("Key auto-generation is not supported by the LanceDB provider.");
        }

        Type keyType = keyProperty.Type;
        if (!LanceDbDataTypes.IsKey(keyType))
        {
            throw new NotSupportedException($"Key type '{keyType.Name}' is not supported by the LanceDB provider. Supported key types are string, Guid, int, and long.");
        }
    }
}
